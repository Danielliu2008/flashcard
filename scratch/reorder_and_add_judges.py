def reorder_and_enrich():
    units = [
        "overview_system", "skeletal_system", "muscular_system", "nervous_system",
        "endocrine_system", "sensory_system", "circulatory_system", "blood_system",
        "respiratory_system", "digestive_system", "urinary_system", "reproductive_system",
        "metabolism_system"
    ]

    for unit in units:
        base_path = os.path.join(ASSETS_DIR, "quizzes", f"{unit}.json")
        if not os.path.exists(base_path):
            continue

        with open(base_path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        raw_qs = data.get('quiz') or data.get('questions') or []

        # 1. 提取并归类现有题目
        single_qs = []
        multi_qs = []
        judge_qs = []
        fill_qs = []

        for q in raw_qs:
            q_type = q.get('type', '')
            q_text = q.get('question') or q.get('prompt') or ''
            opts = q.get('answerOptions') or q.get('options') or []
            blanks = q.get('blankAnswers') or q.get('blanks') or []
            is_j = q_type == 'judge' or q_text.startswith('【判断题】') or (
                len(opts) == 2 and any(o['text'] in ['正确', '对', '√'] for o in opts) and any(o['text'] in ['错误', '错', '×'] for o in opts)
            )

            if blanks or q_type in ['fill_blank', 'fill_in_blank']:
                q['type'] = 'fill_blank'
                fill_qs.append(q)
            elif is_j:
                q['type'] = 'judge'
                if not q_text.startswith('【判断题】'):
                    q['question'] = f"【判断题】{q_text}"
                    q['prompt'] = q['question']
                # 规范选项为“正确”与“错误”
                corr = any(o['isCorrect'] for o in opts if o['text'] in ['正确', '对', '√'])
                q['answerOptions'] = [
                    {"text": "正确", "isCorrect": corr, "rationale": q.get('rationale', '') if corr else ""},
                    {"text": "错误", "isCorrect": not corr, "rationale": q.get('rationale', '') if not corr else ""}
                ]
                q['options'] = q['answerOptions']
                judge_qs.append(q)
            elif q_type == 'multiple_select' or (q_type == 'multiple_choice' and sum(1 for o in opts if o.get('isCorrect')) > 1):
                q['type'] = 'multiple_select'
                multi_qs.append(q)
            else:
                q['type'] = 'single_choice'
                single_qs.append(q)

        # 2. 注入新判断题
        if unit in JUDGES_DATA:
            existing_judge_texts = set(j['question'].replace('【判断题】', '').strip() for j in judge_qs)
            for prompt, is_t, rat in JUDGES_DATA[unit]:
                clean_p = prompt.strip()
                if clean_p not in existing_judge_texts:
                    new_q = {
                        "type": "judge",
                        "question": f"【判断题】{clean_p}",
                        "prompt": f"【判断题】{clean_p}",
                        "answerOptions": [
                            {"text": "正确", "isCorrect": is_t, "rationale": rat if is_t else ""},
                            {"text": "错误", "isCorrect": not is_t, "rationale": rat if not is_t else ""}
                        ],
                        "options": [
                            {"text": "正确", "isCorrect": is_t, "rationale": rat if is_t else ""},
                            {"text": "错误", "isCorrect": not is_t, "rationale": rat if not is_t else ""}
                        ],
                        "blankAnswers": [],
                        "blanks": [],
                        "rationale": rat,
                        "hint": ""
                    }
                    judge_qs.append(new_q)

        # 3. 严格排序：【单选题】 -> 【多选题】 -> 【判断题】 -> 【填空题】（把选择放前面！）
        combined = []
        for q_list in [single_qs, multi_qs, judge_qs, fill_qs]:
            for q in q_list:
                combined.append(q)

        # 重新编号
        for idx, q in enumerate(combined, 1):
            q['c'] = str(idx)
            q['id'] = idx

        data['quiz'] = combined
        data['questions'] = combined

        # 保存到两个目录
        for base in [ASSETS_DIR, SUBJECTS_DIR]:
            p = os.path.join(base, "quizzes", f"{unit}.json")
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, 'w', encoding='utf-8') as out_f:
                json.dump(data, out_f, ensure_ascii=False, indent=2)

        print(f"Updated {unit}: {len(single_qs)} Single, {len(multi_qs)} Multi, {len(judge_qs)} Judges, {len(fill_qs)} Fill -> Total {len(combined)}")

reorder_and_enrich()
