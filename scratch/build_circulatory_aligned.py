def validate(deck: dict, quiz: dict) -> None:
    # Deck validations
    cards = deck["flashcards"]
    assert len(cards) == 28, f"Expected 28 cards, got {len(cards)}"
    fronts = []
    for i, c in enumerate(cards, 1):
        assert c["c"] == i, f"Card index mismatch: {c['c']} != {i}"
        assert c["pointType"] in LEVEL_META, f"Invalid pointType: {c['pointType']}"
        front = c["f"]["flashcardContentBlock"][0]["content"]
        back = c["b"]["flashcardContentBlock"][0]["content"]
        assert front not in fronts, f"Duplicate card front: {front}"
        fronts.append(front)
        assert len(back) <= 130, f"Card {i} back too long ({len(back)} chars): {back}"

    # Quiz validations
    qs = quiz["questions"]
    assert len(qs) == 48, f"Expected 48 questions, got {len(qs)}"
    assert qs == quiz["quiz"], "questions and quiz arrays must be identical"
    assert quiz["topics"]["covered"] == quiz["coveredTopics"] and len(quiz["coveredTopics"]) > 0

    for i, q in enumerate(qs):
        assert q["id"] == i + 1 and q["c"] == str(i + 1)
        assert q["answerOptions"] == q["options"]
        assert q["blankAnswers"] == q["blanks"]
        if i < 18:
            assert q["type"] == "single_choice", f"Q{i+1} type mismatch"
            assert len(q["answerOptions"]) == 4
            assert sum(1 for o in q["answerOptions"] if o["isCorrect"]) == 1
        elif i < 25:
            assert q["type"] == "multiple_select", f"Q{i+1} type mismatch"
            assert len(q["answerOptions"]) == 5
            correct_cnt = sum(1 for o in q["answerOptions"] if o["isCorrect"])
            assert 2 <= correct_cnt <= 4, f"Q{i+1} correct count {correct_cnt}"
        elif i < 37:
            assert q["type"] == "judge", f"Q{i+1} type mismatch"
            opts = q["answerOptions"]
            assert len(opts) == 2 and opts[0]["text"] == "正确" and opts[1]["text"] == "错误"
            assert sum(1 for o in opts if o["isCorrect"]) == 1
            if opts[0]["isCorrect"]:
                assert q["rationale"].startswith("正确"), f"Q{i+1} rationale mismatch"
            else:
                assert q["rationale"].startswith("错误"), f"Q{i+1} rationale mismatch"
        else:
            assert q["type"] == "fill_blank", f"Q{i+1} type mismatch"
            assert q["question"].count("____") == len(q["blankAnswers"]), f"Q{i+1} blank count mismatch"

    # Check single_choice correct index balance
    dist = [0, 0, 0, 0]
    for q in qs[:18]:
        idx = next(j for j, o in enumerate(q["answerOptions"]) if o["isCorrect"])
        dist[idx] += 1
    assert all(3 <= d <= 6 for d in dist), f"Imbalanced single_choice correct distribution: {dist}"
    print(f"Validation passed! Cards={len(cards)}, Questions={len(qs)}, SingleChoice dist={dist}")


