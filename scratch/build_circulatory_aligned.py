def make_single(qid: int, prompt: str, correct_text: str, wrong_texts: list[str], rationale: str, hint: str, rng: random.Random) -> dict:
    opts = [{"text": correct_text, "isCorrect": True, "rationale": rationale}]
    for w in wrong_texts:
        opts.append({"text": w, "isCorrect": False, "rationale": ""})
    rng.shuffle(opts)
    return {
        "c": str(qid),
        "type": "single_choice",
        "question": prompt,
        "prompt": prompt,
        "answerOptions": opts,
        "options": [dict(o) for o in opts],
        "blankAnswers": [],
        "blanks": [],
        "rationale": rationale,
        "hint": hint,
        "id": qid,
    }


def make_multi(qid: int, prompt: str, correct_texts: list[str], wrong_texts: list[str], rationale: str, hint: str, rng: random.Random) -> dict:
    opts = [{"text": t, "isCorrect": True, "rationale": rationale} for t in correct_texts]
    opts.extend({"text": t, "isCorrect": False, "rationale": ""} for t in wrong_texts)
    rng.shuffle(opts)
    return {
        "c": str(qid),
        "type": "multiple_select",
        "question": prompt,
        "prompt": prompt,
        "answerOptions": opts,
        "options": [dict(o) for o in opts],
        "blankAnswers": [],
        "blanks": [],
        "rationale": rationale,
        "hint": hint,
        "id": qid,
    }


def make_judge(qid: int, prompt: str, is_true: bool, rationale: str, hint: str = "结合课程要点概念与机制进行正误判断") -> dict:
    opts = [
        {"text": "正确", "isCorrect": is_true, "rationale": rationale if is_true else ""},
        {"text": "错误", "isCorrect": not is_true, "rationale": rationale if not is_true else ""},
    ]
    return {
        "c": str(qid),
        "type": "judge",
        "question": prompt,
        "prompt": prompt,
        "answerOptions": opts,
        "options": [dict(o) for o in opts],
        "blankAnswers": [],
        "blanks": [],
        "rationale": rationale,
        "hint": hint,
        "id": qid,
    }


